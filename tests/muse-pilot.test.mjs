test('connector only permits four scoped actions and requires exact approval',async()=>{
  const id=randomUUID();
  for(const action of ['finance','income','clinical_context','assign','send','proxy']) assert.throws(()=>validateAction({action}));
  assert.throws(()=>validateAction({action:'list_chats',tenant_id:id}));
  assert.throws(()=>validateAction({action:'read_chat',conversation_id:'../other'}));
  assert.throws(()=>validateAction({action:'send_reply',draft_id:id,confirmation_token:token(),confirmed:false}));
  assert.throws(()=>validateAction({action:'send_reply',draft_id:id,confirmation_token:token(),confirmed:true,content:'alterado'}));
  assert.throws(()=>validateAction({action:'prepare_reply',conversation_id:id,content:' '}));
  assert.equal(validateAction({action:'send_reply',draft_id:id,confirmation_token:token(),confirmed:true}).draft_id,id);
  assert.equal((await hash(token())).length,64);
  assert.deepEqual(Object.keys(chatDto({id,contact_name:'Prueba',phone:'private',balance:50})),['id','name','channel','unread_count']);
  assert.equal('media_url' in messageDto({id,content:'Prueba',media_url:'secret'}),false);
});
test('webhook rejects tampering and old requests while allowing a freshly signed retry',async()=>{
  const secret=token(),now=Date.now();
  const sign=s=>'sha256='+createHmac('sha256',secret).update(s).digest('hex');
  const body=JSON.stringify({event_id:randomUUID(),sent_at:new Date(now).toISOString()});
  assert.equal(await verifyWebhook(body,sign(body),secret,now),true);
  assert.equal(await verifyWebhook(body+' ',sign(body),secret,now),false);
  assert.equal(await verifyWebhook(body,sign(body),secret,now+300001),false);
  assert.equal(await verifyWebhook(body,sign(body),'',now),false);
});

