const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const http=require('node:http');
const root=path.resolve(__dirname,'..');
const out=path.resolve(root,'../output/prescriptions-professional-v2');
fs.mkdirSync(out,{recursive:true});
let playwright;
try{playwright=require('playwright');}catch(e){playwright=require(path.join(process.env.SMYL_NODE_MODULES||path.join(require('node:os').homedir(),'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules'),'playwright'));}

test('receta profesional: preparar, reutilizar y revisar en escritorio y móvil',{timeout:120000},async t=>{
  const server=http.createServer((req,res)=>{const file=path.resolve(root,'.'+decodeURIComponent(req.url.split('?')[0]));if(!file.startsWith(root+path.sep)){res.writeHead(403);return res.end();}try{const body=fs.readFileSync(file);res.setHeader('Content-Type',file.endsWith('.js')?'text/javascript; charset=utf-8':file.endsWith('.css')?'text/css; charset=utf-8':'text/html; charset=utf-8');res.end(body);}catch{res.writeHead(404);res.end();}});
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));t.after(()=>new Promise(resolve=>server.close(resolve)));
  const browser=await playwright.chromium.launch({headless:true,channel:'chrome'});t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(()=>{window.print=()=>{window.__printRequested=true;};});
  await page.goto('http://127.0.0.1:'+server.address().port+'/tests/fixtures/smyl-prescription-professional-v2-preview.html');
  const dialog=page.locator('.rx-dialog');await dialog.waitFor();
  assert.match(await dialog.innerText(),/Preparar[\s\S]*Revisar[\s\S]*Emitir/);
  await dialog.getByRole('button',{name:'Usar como base'}).click();
  assert.equal(await dialog.getByLabel('Nombre genérico *').inputValue(),'Amoxicilina');
  assert.match(await dialog.locator('.rx-allergy-card').innerText(),/Ibuprofeno/);
  assert.ok(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth+1),'sin desborde en escritorio');
  await page.screenshot({path:path.join(out,'preparar-desktop.png')});
  await dialog.getByRole('button',{name:'Revisar receta'}).click();
  assert.match(await dialog.locator('.rx-review').innerText(),/Confirmación profesional/);
  assert.equal(await dialog.locator('.rx-editor').isVisible(),false,'edición oculta durante la revisión');
  assert.equal(await dialog.locator('.rx-aside').isVisible(),false,'resumen lateral oculto durante la revisión');
  const dialogBox=await dialog.boundingBox(),reviewBox=await dialog.locator('.rx-review').boundingBox();
  assert.ok(Math.abs((dialogBox.x+dialogBox.width/2)-(reviewBox.x+reviewBox.width/2))<4,'revisión centrada en escritorio');
  await page.screenshot({path:path.join(out,'revisar-desktop.png')});
  await dialog.getByRole('button',{name:'Volver a editar'}).click();
  await page.setViewportSize({width:390,height:844});
  assert.ok(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth+1),'sin desborde en móvil');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'página móvil sin desborde');
  await page.screenshot({path:path.join(out,'preparar-mobile.png')});
  await dialog.getByRole('button',{name:'Revisar receta'}).click();
  assert.equal(await dialog.locator('.rx-editor').isVisible(),false,'edición móvil oculta durante la revisión');
  assert.equal(await dialog.locator('.rx-aside').isVisible(),false,'historial móvil oculto durante la revisión');
  await dialog.locator('.rx-check input').nth(0).check();await dialog.locator('.rx-check input').nth(1).check();
  await page.screenshot({path:path.join(out,'revisar-mobile.png')});
  await dialog.getByRole('button',{name:'Emitir e imprimir'}).click();
  await dialog.getByText('RX-000019',{exact:true}).waitFor();
  assert.match(await dialog.locator('.rx-done').innerText(),/copia quedó congelada en el expediente/i);
  await page.waitForFunction(()=>window.__printRequested===true);
  await page.screenshot({path:path.join(out,'emitida-mobile.png')});
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(out,'result.json'),JSON.stringify({ok:true,viewports:[1440,390],errors},null,2));
});
